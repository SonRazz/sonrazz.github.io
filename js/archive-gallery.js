function createArchiveItem(item) {
  return `
    <div class="image">
      <a href="${item.full}" class="glightbox">
        <img src="images/thumb-effect.png" class="effect">
        <img src="${item.thumb}" class="crop">
        <div class="overlay">
          <div class="title"></div>
          <p class="info">${item.title}</p>
        </div>
      </a>
    </div>
  `;
}

function renderArchiveGallery() {
  const years = Object.keys(archiveGalleryData).sort((a, b) => b - a);
  const container = document.getElementById("archive-gallery");
  if (!container) return;

  let html = "";

  years.forEach(year => {
    const items = archiveGalleryData[year];
    if (!items || items.length === 0) return;

    html += `<h1>> ${year}</h1>`;
    html += `<div class="gallery">`;
    html += items.map(createArchiveItem).join("");
    html += `</div>`;
  });

  container.innerHTML = html;

  // Inicializar GLightbox
  if (typeof GLightbox !== "undefined") {
    GLightbox({ selector: ".glightbox" });
  }
}

document.addEventListener("DOMContentLoaded", renderArchiveGallery);
